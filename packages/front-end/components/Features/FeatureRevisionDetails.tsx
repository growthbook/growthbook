import { ReactNode, useRef } from "react";
import { Box, Flex } from "@radix-ui/themes";
import { ago, datetime } from "shared/dates";
import { MinimalFeatureRevisionInterface } from "shared/types/feature-revision";
import { ACTIVE_DRAFT_STATUSES } from "shared/validators";
import EventUser from "@/components/Avatar/EventUser";
import Markdown from "@/components/Markdown/Markdown";
import { NamedRevision } from "@/components/Reviews/RevisionLabel";
import RevisionStatusBadge from "@/components/Reviews/RevisionStatusBadge";
import useIsOverflowing from "@/hooks/useIsOverflowing";
import Text from "@/ui/Text";
import { QuickEditRow } from "@/components/Experiment/TabbedPage/QuickEditButton";

const NOTES_MAX_HEIGHT = 100;
// Fits the longest label on one line, so the values share a left edge.
const LABEL_WIDTH = "96px";

// A label column and its value, like the experiment Setup page's rows.
function DetailRow({
  label,
  children,
}: {
  label: string;
  children: ReactNode;
}) {
  return (
    <Flex align="baseline" gap="3">
      <Box flexShrink="0" width={LABEL_WIDTH}>
        <Text weight="medium" color="text-high" whiteSpace="nowrap">
          {label}
        </Text>
      </Box>
      <Box flexGrow="1" minWidth="0" style={{ color: "var(--color-text-mid)" }}>
        {children}
      </Box>
    </Flex>
  );
}

// What the revision selector shows about a revision on hover.
export default function FeatureRevisionDetails({
  revision,
  liveVersion,
  onEditDescription,
}: {
  revision: MinimalFeatureRevisionInterface;
  liveVersion: number;
  // Offered on drafts only; published revisions keep what they shipped with.
  onEditDescription?: () => void;
}) {
  const notes = useRef<HTMLDivElement>(null);
  const notesOverflow = useIsOverflowing(notes, NOTES_MAX_HEIGHT);
  const isDraft = (ACTIVE_DRAFT_STATUSES as readonly string[]).includes(
    revision.status,
  );
  const createdBy = revision.createdBy;
  const editDescription = isDraft ? onEditDescription : undefined;

  return (
    <Flex direction="column" gap="3" style={{ width: 360 }}>
      <Flex align="center" justify="between" gap="3">
        <Text weight="semibold">
          <NamedRevision version={revision.version} title={revision.title} />
        </Text>
        <RevisionStatusBadge revision={revision} liveVersion={liveVersion} />
      </Flex>
      <Flex direction="column" gap="2">
        {isDraft &&
        revision.baseVersion !== undefined &&
        revision.baseVersion !== liveVersion ? (
          <DetailRow label="Based on">
            Revision {revision.baseVersion}
          </DetailRow>
        ) : null}
        {createdBy?.type === "dashboard" || createdBy?.type === "api_key" ? (
          <DetailRow label="Revised by">
            <EventUser user={createdBy} display="avatar-name-email" size="sm" />
          </DetailRow>
        ) : createdBy?.type === "system" ? (
          <DetailRow label="Generated by">
            <em>
              {createdBy.subtype === "ramp-schedule"
                ? "ramp schedule"
                : "system"}
            </em>
          </DetailRow>
        ) : null}
        {revision.status === "published" && revision.datePublished ? (
          <DetailRow label="Published">
            {datetime(revision.datePublished)}
          </DetailRow>
        ) : (
          <DetailRow label="Last update">{ago(revision.dateUpdated)}</DetailRow>
        )}
        {isDraft && revision.scheduledPublishAt ? (
          <DetailRow label="Scheduled">
            {datetime(revision.scheduledPublishAt)}
          </DetailRow>
        ) : null}
        {revision.comment || editDescription ? (
          <DetailRow label="Description">
            <QuickEditRow label="Edit description" onEdit={editDescription}>
              {revision.comment ? (
                <Box
                  className={
                    notesOverflow ? "fade-mask-bottom-1rem" : undefined
                  }
                  style={{ maxHeight: NOTES_MAX_HEIGHT, overflow: "hidden" }}
                >
                  <div ref={notes}>
                    <Markdown>{revision.comment}</Markdown>
                  </div>
                </Box>
              ) : (
                <Text weight="regular" color="text-mid" fontStyle="italic">
                  None
                </Text>
              )}
            </QuickEditRow>
          </DetailRow>
        ) : null}
      </Flex>
    </Flex>
  );
}
