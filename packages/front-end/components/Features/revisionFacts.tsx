import { Fragment, ReactNode } from "react";
import { Flex } from "@radix-ui/themes";
import { ago, datetime } from "shared/dates";
import { MinimalFeatureRevisionInterface } from "shared/types/feature-revision";
import {
  EventUser as EventUserType,
  eventUserIdentity,
  eventUserPersonId,
  isActiveDraftStatus,
  revisionActor,
} from "shared/validators";
import EventUser from "@/components/Avatar/EventUser";
import Text from "@/ui/Text";

export type RevisionFact = { label: string; value: ReactNode };

// A member as revision details draw people; a key acting as itself by its name.
export function revisionActorValue(
  user: EventUserType,
  person: (id: string) => ReactNode,
): ReactNode {
  const personId = eventUserPersonId(user);
  return personId ? (
    person(personId)
  ) : (
    <Text size="sm" color="text-mid">
      <EventUser user={user} display="avatar-name" size="xs" />
    </Text>
  );
}

// What a revision's details say about it, in order, wherever they're listed.
export function revisionFacts(
  revision: MinimalFeatureRevisionInterface,
  liveVersion: number,
  // A teammate, drawn as the list draws people.
  person: (id: string) => ReactNode,
): RevisionFact[] {
  const facts: RevisionFact[] = [];
  const isDraft = isActiveDraftStatus(revision.status);

  if (
    isDraft &&
    revision.baseVersion !== undefined &&
    revision.baseVersion !== liveVersion
  ) {
    facts.push({
      label: "Based on",
      value: `Revision ${revision.baseVersion}`,
    });
  }

  const actor = (user: EventUserType) => revisionActorValue(user, person);

  const createdBy = revision.createdBy;
  if (createdBy?.type === "dashboard" || createdBy?.type === "api_key") {
    facts.push({ label: "Revised by", value: actor(createdBy) });
  } else if (createdBy?.type === "system") {
    facts.push({
      label: "Generated by",
      value: createdBy.subtype === "ramp-schedule" ? "Ramp schedule" : "System",
    });
  }

  // Contributors are identities: members, or keys that acted as themselves.
  const authorIdentity = eventUserIdentity(createdBy ?? null);
  const coAuthorIds = (revision.contributors ?? []).filter(
    (id) => id !== authorIdentity,
  );
  if (coAuthorIds.length > 0) {
    facts.push({
      label: coAuthorIds.length === 1 ? "Co-author" : "Co-authors",
      value: (
        <Flex direction="column" gap="1">
          {coAuthorIds.map((id) => (
            <Fragment key={id}>{actor(revisionActor(revision, id))}</Fragment>
          ))}
        </Flex>
      ),
    });
  }

  facts.push(
    revision.status === "published" && revision.datePublished
      ? { label: "Published", value: datetime(revision.datePublished) }
      : { label: "Last update", value: ago(revision.dateUpdated) },
  );

  if (isDraft && revision.scheduledPublishAt) {
    facts.push({
      label: "Publishes",
      value: datetime(revision.scheduledPublishAt),
    });
  }

  return facts;
}
